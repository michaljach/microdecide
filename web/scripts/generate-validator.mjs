// Compile Python's JSON Schema ahead of time: no schema compiler or eval in the browser.
import { readFileSync, writeFileSync } from "node:fs";
import Ajv from "ajv/dist/2020.js";
import standaloneCode from "ajv/dist/standalone/index.js";

const schema = JSON.parse(readFileSync(new URL("../src/model.schema.json", import.meta.url), "utf8"));
const ajv = new Ajv({ strict: false, allErrors: true, code: { source: true, esm: true } });
const code = "// @ts-nocheck\n// Generated by scripts/generate-validator.mjs. Do not edit.\n" + standaloneCode(ajv, ajv.compile(schema)) + "\n";
const path = new URL("../src/model-validator.ts", import.meta.url);
if (process.argv.includes("--check")) {
  if (readFileSync(path, "utf8") !== code) throw new Error("Artifact validator is stale: npm run schema");
} else writeFileSync(path, code);
